export function resolveCanadianProvince(value: unknown): string | null {
  const normalized = String(value ?? '').trim().toLowerCase()
    .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
    .replace(/\./g, '')
    .replace(/[\s-]+/g, ' ');
  if (!normalized) return null;
  return PROVINCE_ALIASES[normalized] ??
    Object.keys(CANADIAN_EDUCATION_BOARDS_BY_PROVINCE)
      .concat('Ontario')
      .find((province) => province.toLowerCase() === normalized) ?? null;
}
